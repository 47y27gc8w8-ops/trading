"""Evolutionary strategy improvement: mutate -> backtest -> keep if better.

Usage (inside the container; use scripts/evolve.sh on the host so results get
committed to git):

    python -m src.backtest.evolve <strategy> --generations 20        # random param mutations
    python -m src.backtest.evolve <strategy> --set fast=40 --note ".."  # one hand-picked change
    python -m src.backtest.evolve <strategy> --code-change --note ".."  # judge an edit to strategy.py

Rules
- Every candidate is backtested on the in-sample window (before `oos_start`).
  Fitness = in-sample Sharpe. A candidate replaces the champion only if it
  beats it by at least `min_improvement`.
- The out-of-sample window (from `oos_start`) is recorded for every candidate
  but NEVER used to accept/reject, so it stays an honest check for overfitting.
- Every experiment, kept or not, is appended to experiments.jsonl and the
  EVOLUTION.md report is regenerated.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import importlib.util
import json
import random
import sys
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from . import engine
from .metrics import stats

ROOT = Path(__file__).resolve().parents[2]
STRATS = ROOT / "strategies"


def load_strategy(name: str):
    d = STRATS / name
    spec = importlib.util.spec_from_file_location(f"strategies.{name}", d / "strategy.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    cfg = json.loads((d / "config.json").read_text())
    return d, mod, cfg


def code_hash(d: Path) -> str:
    return hashlib.sha256((d / "strategy.py").read_bytes()).hexdigest()[:10]


def evaluate(mod, cfg: dict, params: dict) -> dict:
    res = engine.run(mod, cfg, params)
    ppy = cfg.get("periods_per_year", 252)
    cut = pd.Timestamp(cfg["oos_start"], tz="UTC")
    out = {}
    for label, sel in (("is", lambda s: s[s.index < cut]), ("oos", lambda s: s[s.index >= cut])):
        out[label] = stats(sel(res["returns"]), ppy, res["exposure"], res["turnover"])
        out[f"bench_{label}"] = stats(sel(res["benchmark"]), ppy)
    out["fitness"] = out["is"].get(cfg.get("fitness", "sharpe"), float("nan"))
    if out["fitness"] != out["fitness"]:  # NaN
        out["fitness"] = -99.0
    return out


def mutate(params: dict, space: dict, rng: random.Random) -> tuple[dict, str]:
    p = copy.deepcopy(params)
    keys = rng.sample(list(space), k=min(len(space), rng.choice([1, 1, 1, 2])))
    changes = []
    for k in keys:
        spec, old = space[k], p[k]
        if "choices" in spec:
            opts = [c for c in spec["choices"] if c != old]
            if not opts:
                continue
            p[k] = rng.choice(opts)
        else:
            step = spec["step"] * rng.choice([-3, -2, -1, 1, 2, 3])
            new = min(spec["max"], max(spec["min"], old + step))
            p[k] = int(round(new)) if isinstance(spec["step"], int) else round(new, 6)
        if p[k] != old:
            changes.append(f"{k} {old}->{p[k]}")
    return p, ", ".join(changes)


def read_log(d: Path) -> list[dict]:
    f = d / "experiments.jsonl"
    return [json.loads(l) for l in f.read_text().splitlines() if l.strip()] if f.exists() else []


def append_log(d: Path, rec: dict) -> None:
    with open(d / "experiments.jsonl", "a") as f:
        f.write(json.dumps(rec, default=str) + "\n")


def fmt(x, pct=False):
    if x is None or x != x:
        return "–"
    return f"{x*100:.1f}%" if pct else f"{x:.2f}"


def write_report(d: Path, cfg: dict, log: list[dict]) -> None:
    champ = cfg.get("champion", {})
    lines = [
        f"# Evolution log: {d.name}",
        "",
        "Generated by `src/backtest/evolve.py`; do not edit by hand. Raw data is in `experiments.jsonl`.",
        "",
        f"- Universe: {', '.join(cfg['universe'])} ({cfg['asset_class']}), costs {cfg.get('cost_bps', 10)} bps per unit of turnover",
        f"- In-sample: up to {cfg['oos_start']} (used for keep/discard). Out-of-sample: from {cfg['oos_start']} (holdout, never used for decisions)",
        f"- Fitness: in-sample {cfg.get('fitness', 'sharpe')}; a change is kept only if it improves fitness by at least {cfg.get('min_improvement', 0.02)}",
        "",
        "## Current champion",
        "",
        f"`{json.dumps(cfg['params'])}` (code `{champ.get('code', '?')}`, experiment #{champ.get('id', '?')})",
        "",
    ]
    if champ:
        lines += [
            "| window | Sharpe | CAGR | Max DD | Calmar | Exposure | Buy&hold Sharpe | Buy&hold CAGR | Buy&hold Max DD |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for w in ("is", "oos"):
            s, b = champ.get(w, {}), champ.get(f"bench_{w}", {})
            lines.append(
                f"| {w.upper()} {s.get('start', '')}..{s.get('end', '')} | {fmt(s.get('sharpe'))} | {fmt(s.get('cagr'), 1)} | "
                f"{fmt(s.get('max_dd'), 1)} | {fmt(s.get('calmar'))} | {fmt(s.get('avg_exposure'), 1)} | "
                f"{fmt(b.get('sharpe'))} | {fmt(b.get('cagr'), 1)} | {fmt(b.get('max_dd'), 1)} |"
            )
    kept = sum(r["accepted"] for r in log)
    lines += [
        "",
        f"## All experiments ({len(log)} total, {kept} kept, {len(log) - kept} discarded)",
        "",
        "| # | date | kind | change | IS Sharpe | IS CAGR | IS MaxDD | OOS Sharpe | OOS CAGR | result | note |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in reversed(log):
        i, o = r["is"], r["oos"]
        res = "KEPT" if r["accepted"] else f"discarded (champion {fmt(r['champion_fitness_before'])})"
        lines.append(
            f"| {r['id']} | {r['ts'][:10]} | {r['kind']} | {r['change'] or '–'} | {fmt(i.get('sharpe'))} | "
            f"{fmt(i.get('cagr'), 1)} | {fmt(i.get('max_dd'), 1)} | {fmt(o.get('sharpe'))} | {fmt(o.get('cagr'), 1)} | {res} | {r.get('note') or ''} |"
        )
    (d / "EVOLUTION.md").write_text("\n".join(lines) + "\n")


def record(d, cfg, log, kind, params, change, ev, note) -> dict:
    champ_fit = cfg.get("champion", {}).get("fitness")
    accepted = champ_fit is None or ev["fitness"] >= champ_fit + cfg.get("min_improvement", 0.02)
    rec = {
        "id": len(log) + 1, "ts": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "kind": kind, "code": code_hash(d), "params": params, "change": change, "note": note,
        "fitness": ev["fitness"], "champion_fitness_before": champ_fit, "accepted": accepted,
        "is": ev["is"], "oos": ev["oos"], "bench_is": ev["bench_is"], "bench_oos": ev["bench_oos"],
    }
    append_log(d, rec)
    log.append(rec)
    if accepted:
        cfg["params"] = params
        cfg["champion"] = {"id": rec["id"], "code": rec["code"], "fitness": ev["fitness"],
                           **{k: ev[k] for k in ("is", "oos", "bench_is", "bench_oos")}}
    flag = "KEPT     " if accepted else "discarded"
    print(f"#{rec['id']:>3} {flag} fit={ev['fitness']:+.3f} (champ {champ_fit if champ_fit is None else round(champ_fit, 3)}) "
          f"OOS sharpe={ev['oos'].get('sharpe')} | {change or kind}", flush=True)
    return rec


def parse_set(items: list[str], params: dict) -> dict:
    p = copy.deepcopy(params)
    for it in items:
        k, v = it.split("=", 1)
        p[k] = json.loads(v) if v[:1] in "-0123456789[{tf\"" else v
    return p


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("strategy")
    ap.add_argument("--generations", type=int, default=0)
    ap.add_argument("--set", nargs="*", default=[], help="hand-picked param change, e.g. fast=40")
    ap.add_argument("--code-change", action="store_true", help="judge the current strategy.py against the champion")
    ap.add_argument("--tune", type=int, default=0,
                    help="with --code-change: hill-climb the new code's params for N steps before giving up")
    ap.add_argument("--only", default="", help="comma-separated params that mutations may change")
    ap.add_argument("--note", default="")
    ap.add_argument("--seed", type=int)
    a = ap.parse_args()

    d, mod, cfg = load_strategy(a.strategy)
    valid = getattr(mod, "valid", lambda p: True)
    log = read_log(d)
    tested = {json.dumps(r["params"], sort_keys=True) + r["code"] for r in log}
    rng = random.Random(a.seed)
    space = {k: v for k, v in cfg["space"].items() if not a.only or k in a.only.split(",")}
    kept, ran, last_id = [], 0, None

    def save():
        (d / "config.json").write_text(json.dumps(cfg, indent=2) + "\n")
        write_report(d, cfg, log)

    if "champion" not in cfg:  # first run: baseline from the published rules
        rec = record(d, cfg, log, "baseline", cfg["params"], "", evaluate(mod, cfg, cfg["params"]), a.note or "published default rules")
        ran += 1; last_id = rec["id"]; save()
        a.code_change = False  # the baseline already measured the current code
        a.note = ""

    if a.code_change:
        ev = evaluate(mod, cfg, cfg["params"])
        rec = record(d, cfg, log, "code", cfg["params"], "strategy.py edited", ev, a.note)
        ran += 1; last_id = rec["id"]; kept += [rec] if rec["accepted"] else []; save()
        # Tuning: hill-climb the NEW code's params from its own best point, so a
        # good idea with bad default params is not thrown away. Every step must
        # still beat the old champion by min_improvement to be kept.
        best_p, best_fit = rec["params"], ev["fitness"]
        tested.add(json.dumps(best_p, sort_keys=True) + code_hash(d))
        for _ in range(a.tune):
            for _try in range(200):
                p, change = mutate(best_p, space, rng)
                key = json.dumps(p, sort_keys=True) + code_hash(d)
                if change and valid(p) and key not in tested:
                    break
            else:
                print("tuning space exhausted"); break
            tested.add(key)
            ev = evaluate(mod, cfg, p)
            rec = record(d, cfg, log, "tune", p, change, ev, a.note)
            ran += 1; last_id = rec["id"]; kept += [rec] if rec["accepted"] else []; save()
            if ev["fitness"] > best_fit:
                best_p, best_fit = p, ev["fitness"]
        if not kept:
            print(f"EXPERIMENT_ID: {last_id}\nREJECTED_CODE_CHANGE")
            print(f"COMMIT_MSG: evolve({a.strategy}): code change rejected after {ran} experiments "
                  f"(best tuned IS fitness {best_fit:.3f} vs champion {cfg['champion']['fitness']:.3f}) {a.note}")
            return 3

    if a.set:
        p = parse_set(a.set, cfg["params"])
        change = ", ".join(f"{k} {cfg['params'].get(k)}->{p[k]}" for k in p if p[k] != cfg["params"].get(k))
        if not valid(p):
            print(f"invalid params: {p}", file=sys.stderr); return 2
        rec = record(d, cfg, log, "manual", p, change, evaluate(mod, cfg, p), a.note)
        ran += 1; last_id = rec["id"]; kept += [rec] if rec["accepted"] else []; save()

    for _ in range(a.generations):
        for _try in range(200):
            p, change = mutate(cfg["params"], space, rng)
            key = json.dumps(p, sort_keys=True) + code_hash(d)
            if change and valid(p) and key not in tested:
                break
        else:
            print("search space exhausted around champion"); break
        tested.add(key)
        rec = record(d, cfg, log, "mutation", p, change, evaluate(mod, cfg, p), a.note)
        ran += 1; last_id = rec["id"]; kept += [rec] if rec["accepted"] else []; save()

    if ran == 0:
        # just refresh the report with the current data
        save(); print("nothing to do (use --generations N, --set or --code-change)"); return 0
    champ = cfg["champion"]
    print(f"EXPERIMENT_ID: {last_id}")
    print(f"COMMIT_MSG: evolve({a.strategy}): {ran} experiments, {len(kept)} kept; champion #{champ['id']} "
          f"IS sharpe {champ['is']['sharpe']} / OOS sharpe {champ['oos'].get('sharpe')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
