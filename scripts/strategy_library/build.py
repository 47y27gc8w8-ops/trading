#!/usr/bin/env python3
"""Build strategies/<name>/backtest.py for research-library specs.

Each output is a self-contained adapted copy of strategies/backtest.py (the template is not
modified):
  - the "Strategy definition" block is replaced by defs/<name>.py plus common_block.py
    (INDICATORS.md conventions)
  - _simulate is replaced by simulate_block.py (EXECUTION.md exits: frozen-ATR stop/target,
    max_candles, entry veto, flat bar after intrabar exits)

    python3 scripts/strategy_library/build.py [name ...]     # default: every defs/*.py
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
TEMPLATE = ROOT / "strategies" / "backtest.py"

DEF_START = "# --------------------------------------------------------------------------\n# Strategy definition"
DEF_END = "# --------------------------------------------------------------------------\n# Generic machinery"


def build(name: str) -> Path:
    t = TEMPLATE.read_text()
    a, b = t.index(DEF_START), t.index(DEF_END)
    head = ("# --------------------------------------------------------------------------\n"
            "# Strategy definition (generated by scripts/strategy_library/build.py from\n"
            f"# scripts/strategy_library/defs/{name}.py; edit there and rebuild).\n"
            "# --------------------------------------------------------------------------\n")
    block = head + (HERE / "defs" / f"{name}.py").read_text().rstrip() + "\n\n\n" + (HERE / "common_block.py").read_text().rstrip() + "\n\n"
    t = t[:a] + block + t[b:]
    s0, s1 = t.index("def _simulate("), t.index("def _bounds(")
    t = t[:s0] + (HERE / "simulate_block.py").read_text().rstrip() + "\n\n\n" + t[s1:]
    out = ROOT / "strategies" / name / "backtest.py"
    out.write_text(t)
    return out


if __name__ == "__main__":
    names = sys.argv[1:] or sorted(p.stem for p in (HERE / "defs").glob("*.py"))
    for n in names:
        print(build(n).relative_to(ROOT))
